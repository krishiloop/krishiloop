"""The "Try it yourself" page (/try) runs TypeScript ports of the planner's decision step and the Climate-Smart Shield.

Its rule data and the parity fixtures its web tests check against (apps/web/src/features/try/engine.test.ts) are
generated by tools/build_try_data.py from the rule YAML and the real Python code. This test fails when they drift:
rerun `.venv/Scripts/python.exe -m tools.build_try_data` after changing a rule, the planner or the shield.
"""
import json

from tools import build_try_data as b


def test_try_data_is_fresh():
    stale = [str(p.relative_to(b.ROOT)) for p, text in b.outputs().items()
             if not p.exists() or p.read_text(encoding="utf-8") != text]
    assert stale == [], f"rerun python -m tools.build_try_data: {stale}"


def test_the_fixtures_cover_every_answer_the_tools_can_show():
    plan = json.loads(b.PLAN_FIX.read_text(encoding="utf-8"))["rows"]
    seen = {(r["case"], r["expect"].get("decision") or r["expect"].get("reason")) for r in plan}
    for want in [("rice-tillering", "dont_spray"), ("rice-tillering", "recheck"), ("rice-booting", "dont_spray"),
                 ("rice-booting", "recheck"), ("potato-vegetative", "dont_spray"), ("potato-vegetative", "recheck"),
                 ("potato-vegetative", "no_matching_rule"), ("rice-tillering", "rule_recalled")]:
        assert want in seen, want
    shield = json.loads(b.SHIELD_FIX.read_text(encoding="utf-8"))["rows"]
    levels = {(c["kind"], c["level"]) for r in shield for c in r["expect"]["checks"]}
    for kind in ("heavy_rain", "heat", "flood", "disease"):
        assert (kind, "warn") in levels and (kind, "clear") in levels
    assert any(c["rule_withdrawn"] for r in shield for c in r["expect"]["checks"])


def test_the_rule_data_carries_sources_and_no_new_text():
    data = json.loads(b.RULES_OUT.read_text(encoding="utf-8"))
    for pack in data["packs"].values():
        for r in pack["rules"]:
            assert r["sources"] and all(s["quote"] and s["page"] for s in r["sources"])
            assert all(s["doc_id"] in data["docs"] for s in r["sources"])
