/**
 * KrishiGuard calls (services/api/main.py, "KrishiGuard block"):
 *   GET  /api/climate?field_id&profile_id&snapshot_id&sid   the Climate-Smart Shield for a plan's own forecast
 *   GET  /api/radar                                          real cells (k-anonymous) + the SIMULATED scenario
 *   POST /api/demo/{sid}/radar/warn {area, problem, layer}   a fixed notice to this session's holders in that area
 *   POST /api/demo/{sid}/visit {...}                         "ask an officer to visit or call": an inbox case
 * Without the API (recorded mode) the shield comes from recorded.json and the radar's simulated scenario from
 * ../../officer/radar/simulated.json: both generated by the same Python code (tests/test_climate.py and test_radar.py
 * fail if they drift). Nothing here is invented in the browser; a recorded-mode booking stays in this browser and says so.
 */
import { apiStore, currentSessionId, HttpError, isUnreachable, request, sandbox } from '../../../lib/api/client';
import type { DataSource, Plan } from '../../../lib/api/types';
import { registerLocalCase } from '../../officer/inboxStore';
import type { ClimateReport, FieldArea, RadarAggregate, RadarData, VisitBooking, VisitResult, WarnResult } from './types';

type Recorded = { recorded: Record<string, ClimateReport>; simulated: Record<string, ClimateReport> };
let recordedCall: Promise<Recorded> | null = null;
const loadRecorded = () => (recordedCall ??= import('./recorded.json').then((m) => m.default as unknown as Recorded));

const sampleMode = () => apiStore.get().forced || apiStore.get().mode === 'sample';

export interface ShieldResult {
  report: ClimateReport | null;
  source: 'live' | 'recorded';
}

/** The shield for the plan on screen: live for a live plan, recorded for a recorded one. null report = no forecast. */
export async function fetchShield(plan: Plan, profileId: string | null, planSource: DataSource | null): Promise<ShieldResult> {
  if (planSource !== 'live' || apiStore.get().forced) {
    const r = await loadRecorded();
    return { report: r.recorded[`${plan.field_id}|${profileId ?? ''}`] ?? null, source: 'recorded' };
  }
  const q = new URLSearchParams({ field_id: plan.field_id, snapshot_id: plan.snapshot_id, profile_id: profileId ?? '', sid: currentSessionId() ?? '' });
  try {
    return { report: await request<ClimateReport>(`/api/climate?${q}`), source: 'live' };
  } catch (e) {
    if (isUnreachable(e) || (e instanceof HttpError && e.status === 404)) return { report: null, source: 'live' };
    throw e;
  }
}

/** The made-up stormy week (labelled SIMULATED wherever shown), computed by the same Python on a recorded snapshot. */
export async function simulatedShield(fieldId: string, profileId: string | null): Promise<ClimateReport | null> {
  const r = await loadRecorded();
  return r.simulated[`${fieldId}|${profileId ?? ''}`] ?? null;
}

/* ------------------------------------------------------------------ radar */
type SimFile = {
  simulated: RadarAggregate;
  field_areas: Record<string, FieldArea | null>;
  notice: { en: string; bn: string; sim_prefix: Record<string, string>; problems: Record<string, Record<string, string>> };
};
let simCall: Promise<SimFile> | null = null;
export const loadSimFile = () => (simCall ??= import('../../officer/radar/simulated.json').then((m) => m.default as unknown as SimFile));

let radarCall: Promise<RadarData> | null = null;
let radarAt = 0;

/** Real + simulated radar. Cached for a minute (the farmer card and the officer map share it). */
export function fetchRadar(force = false): Promise<RadarData> {
  if (!force && radarCall && Date.now() - radarAt < 60_000) return radarCall;
  radarAt = Date.now();
  radarCall = (async (): Promise<RadarData> => {
    const recorded = async (): Promise<RadarData> => {
      const s = await loadSimFile();
      return { real: null, simulated: s.simulated, fieldAreas: s.field_areas, source: 'recorded' };
    };
    if (sampleMode()) return recorded();
    try {
      const r = await request<{ real: RadarAggregate; simulated: RadarAggregate; field_areas: Record<string, FieldArea | null> }>('/api/radar');
      return { real: r.real, simulated: r.simulated, fieldAreas: r.field_areas, source: 'live' };
    } catch (e) {
      if (isUnreachable(e)) return recorded();
      throw e;
    }
  })();
  radarCall.catch(() => {
    radarCall = null;
  });
  return radarCall;
}

/** The notice text exactly as services/engine/radar.py words it (recorded mode shows it without sending). */
export async function noticePreview(cell: { reporters: number; area_name: string; problem: string }, simulated: boolean, windowDays: number): Promise<Record<string, string>> {
  const s = await loadSimFile();
  const out: Record<string, string> = {};
  for (const lang of ['en', 'bn'] as const) {
    const word = s.notice.problems[cell.problem]?.[lang] ?? cell.problem.replace(/_/g, ' ');
    const body = s.notice[lang].replace('{n}', String(cell.reporters)).replace('{area}', cell.area_name).replace('{problem}', word).replace('{days}', String(windowDays));
    out[lang] = (simulated ? (s.notice.sim_prefix[lang] ?? '') : '') + body;
  }
  return out;
}

export async function warnNeighbours(cell: { area: string; problem: string; reporters: number; area_name: string }, layer: 'real' | 'simulated', windowDays: number): Promise<WarnResult> {
  if (sampleMode()) {
    return { mode: 'sample', total: 0, sms_sandbox: 0, telegram: 0, failed: 0, recipients: [], text: await noticePreview(cell, layer === 'simulated', windowDays) };
  }
  const body = JSON.stringify({ area: cell.area, problem: cell.problem, layer });
  const r = await sandbox<Omit<WarnResult, 'mode'>>('/radar/warn', { method: 'POST', body });
  return { ...r, mode: 'live' };
}

/* ------------------------------------------------------------------ visit booking */
/** Same masking as services/reach/senders.mask: the first 3 and last 2 digits, the rest as dots. */
export function maskPhone(number: string): string {
  const plus = number.startsWith('+');
  const digits = number.replace(/^\+/, '');
  return (plus ? '+' : '') + digits.slice(0, 3) + '•'.repeat(Math.max(0, digits.length - 5)) + digits.slice(-2);
}

/** Phone as the server takes it: spaces, dashes, dots and brackets dropped; 8 to 15 digits with an optional +. */
export function normalisePhone(raw: string): { ok: boolean; phone: string } {
  const BN = '০১২৩৪৫৬৭৮৯';
  const phone = raw.replace(/[০-৯]/g, (d) => String(BN.indexOf(d))).replace(/[\s\-().]/g, '');
  return { ok: phone === '' || /^\+?[0-9]{8,15}$/.test(phone), phone };
}

export async function requestVisit(b: VisitBooking, farmerLabel: string): Promise<VisitResult> {
  const local = (): VisitResult => {
    const id = `inbox-visit-${Math.random().toString(16).slice(2, 10)}`;
    const masked = b.phone ? maskPhone(b.phone) : null;
    registerLocalCase({
      item_id: id,
      field_id: b.field_id,
      farmer_display_name: farmerLabel,
      reason_code: 'visit_request',
      reason: {
        en: 'Recorded mode: the request was kept in this browser, not sent. The officer decides the time; this demo calls no one.',
        bn: 'রেকর্ড করা মোড: অনুরোধটি এই ব্রাউজারে রাখা হয়েছে, পাঠানো হয়নি। সময় কর্মকর্তা ঠিক করবেন; এই ডেমো কাউকে ফোন করে না।',
      },
      question: b.note || null,
      photo_attached: false,
      status: 'open',
      created_at: new Date().toISOString(),
      details: { kind: 'visit_request', requested_date: b.date, slot: b.slot, mode: b.mode, phone_masked: masked, lang: b.lang, kept: 'this browser only (recorded mode)' },
    });
    return { mode: 'sample', item_id: id, requested_date: b.date, slot: b.slot, phone_masked: masked };
  };
  if (sampleMode()) return local();
  try {
    const r = await sandbox<Omit<VisitResult, 'mode'>>('/visit', { method: 'POST', body: JSON.stringify(b) });
    return { ...r, mode: 'live' };
  } catch (e) {
    if (isUnreachable(e)) return local();
    throw e;
  }
}
