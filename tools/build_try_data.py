"""Data for the "Try it yourself" page (/try, apps/web/src/features/try): the rule packs as JSON, plus parity fixtures.

The page runs two small TypeScript ports in the browser, so a visitor can move sliders and see the answer at once:
- the planner's decision step (services/engine/planner.py make_plan: which input-decision rule fires, or why it
  abstains, plus the two practices it shows next to it) over the rule YAML (rules/registry/*), and
- the Climate-Smart Shield (services/engine/climate.py shield) over rules/climate/shield.yaml.

This script writes:
- apps/web/src/features/try/data/rules.json: the rules (conditions, actions, reviewer parameters, sources with their
  verbatim quotes), the shield's links and team-set thresholds, and the cited documents. DATA from the YAML, no new facts.
- apps/web/src/features/try/fixtures/plan-parity.json and shield-parity.json: a grid of inputs and what the REAL Python
  code answers for each (make_plan with a throwaway trust store; climate.shield). The web tests
  (features/try/engine.test.ts) check the ports give the same answer on every row.

tests/test_try_data.py fails when these files drift from the YAML or the Python code: rerun
`.venv/Scripts/python.exe -m tools.build_try_data` after changing a rule.
"""
from __future__ import annotations

import json
import sys
import tempfile
from datetime import date, timedelta
from pathlib import Path

import yaml

from services.engine import climate
from services.engine import snapshot as snap_mod
from services.engine.planner import PLANNER_VERSION, make_plan
from services.engine.rules import load_pack, manifest, pack_parameter_defs, pack_parameters

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "apps" / "web" / "src" / "features" / "try"
RULES_OUT = OUT_DIR / "data" / "rules.json"
PLAN_FIX = OUT_DIR / "fixtures" / "plan-parity.json"
SHIELD_FIX = OUT_DIR / "fixtures" / "shield-parity.json"
PACKS = ("pack-bd-rice", "pack-potato-late-blight")
TODAY = date(2026, 11, 19)   # fixtures only: the forecast days are dated from here
RULE_KEYS = ("rule_id", "version", "pack_id", "status", "crop", "when", "boost_when", "action", "basis_note")
SOURCE_KEYS = ("doc_id", "page", "quote")
DOC_KEYS = ("title", "publisher", "url", "language", "licence_status")


def rules_json() -> dict:
    docs: dict = {}
    packs: dict = {}
    for pack in PACKS:
        rules = []
        for r in load_pack(pack):
            out = {k: r[k] for k in RULE_KEYS if k in r}
            out["review_level"] = r.get("review", {}).get("level", "pending")
            out["reviewer_parameters"] = r.get("reviewer_parameters", [])
            out["sources"] = [{k: s[k] for k in SOURCE_KEYS} for s in r["sources"]]
            for s in r["sources"]:
                docs[s["doc_id"]] = {k: manifest()[s["doc_id"]].get(k) for k in DOC_KEYS}
            rules.append(out)
        packs[pack] = {"params": pack_parameters(pack), "defs": pack_parameter_defs(pack), "rules": rules}
    shield = yaml.safe_load(climate.SHIELD_YAML.read_text(encoding="utf-8"))
    return {
        "note": "Generated by tools/build_try_data.py from rules/registry/* and rules/climate/shield.yaml. Do not edit.",
        "planner_version": PLANNER_VERSION, "climate_version": climate.CLIMATE_VERSION,
        "window_days": snap_mod.WINDOW_DAYS, "min_days": snap_mod.MIN_DAYS,
        "packs": packs,
        "shield": {"team_params": shield["team_params"], "links": shield["links"], "context": shield.get("context") or {}},
        "docs": dict(sorted(docs.items())),
    }


# ------------------------------------------------------------------ the spray tool's sliders -> a 7-day week
def spray_week(humidity: float, low: float, high: float, rain: float) -> list[dict]:
    """The spray tool's week (mirrored in features/try/engine.ts sprayWeek): every day has the chosen humidity and
    temperatures; the heaviest rain falls on day 1, the other days are dry."""
    return [{"date": (TODAY + timedelta(days=i)).isoformat(), "rh_mean_pct": humidity, "tmin_c": low, "tmax_c": high,
             "precip_mm": rain if i == 0 else 0.0} for i in range(7)]


def _snap(days: list[dict], country: str, flood: dict | None = None) -> dict:
    return {"snapshot_id": "snap-try", "field_id": "TRY", "mode": "live", "created_at": f"{TODAY.isoformat()}T06:00:00Z",
            "location": {"country": country, "precision": "sample_location"},
            "forecast": {"source": "try:practice", "issued_at": f"{TODAY.isoformat()}T06:00:00Z", "days": days},
            "flood": flood}


FIELDS = {
    "rice-tillering": {"field_id": "TRY-BD", "crop": "rice", "stage": "tillering", "pack_id": "pack-bd-rice", "country": "BD"},
    "rice-booting": {"field_id": "TRY-BD", "crop": "rice", "stage": "booting", "pack_id": "pack-bd-rice", "country": "BD"},
    "potato-vegetative": {"field_id": "TRY-KE", "crop": "potato", "stage": "vegetative", "pack_id": "pack-potato-late-blight",
                          "country": "KE"},
}


class _Store:
    """A throwaway stand-in for the trust store: make_plan's logic runs unchanged; only credential minting is faked."""

    def __init__(self, recalled: set[str]):
        self.recalled = recalled
        self.n = 0

    def is_recalled(self, rule_id: str, version: int) -> bool:
        return f"{rule_id}@{version}" in self.recalled

    def trusted_photo_model(self, model: str, area: str):
        return None

    def rule_credential(self, rule: dict) -> dict:
        return {"id": f"urn:uuid:00000000-0000-0000-0000-{self._next():012d}"}

    def receipt_credential(self, receipt: dict, valid_until: str | None = None) -> dict:
        return {"id": f"urn:uuid:00000000-0000-0000-0000-{self._next():012d}"}

    def _next(self) -> int:
        self.n += 1
        return self.n


def plan_fixture() -> dict:
    rows = []
    weeks = [(h, lo, hi, rain) for h in (60, 70, 85, 95) for lo, hi in ((12, 20), (22, 30), (24, 34), (8, 26))
             for rain in (0, 10, 19, 20)]
    bph = [(0, 0), (1, 7), (2, 0), (0, 8), (5, 15)]
    with tempfile.TemporaryDirectory() as tmp:
        inbox_dir = Path(tmp) / "inbox"

        def run(case: str, profile: dict, week: tuple, recalled: tuple[str, ...] = ()):
            field = FIELDS[case]
            days = spray_week(*week)
            plan = make_plan({**field, "lat": 0, "lon": 0}, {"farmer_profile_id": "try", **profile}, _Store(set(recalled)),
                             snap=_snap(days, field["country"]), today=TODAY, inbox_dir=inbox_dir)
            out = {"status": plan["status"]}
            if plan["status"] == "ok":
                out["actions"] = [a["receipt"]["rule_refs"][0]["rule_id"] for a in plan["actions"]]
                out["decision"] = plan["actions"][0].get("decision")
            else:
                out["reason"] = plan["abstention"]["reason_code"]
            rows.append({"case": case, "profile": profile, "week": list(week), "recalled": list(recalled), "expect": out})

        for case in ("rice-tillering", "rice-booting"):
            for f, n in bph:
                for w in weeks:
                    run(case, {"bph_females_per_hill": f, "bph_nymphs_per_hill": n}, w)
        for prot in (False, True):
            for w in weeks:
                run("potato-vegetative", {"crop_protected": prot}, w)
        # a recalled rule is never served: the plan abstains when the decision depended on it
        for w in weeks[::8]:
            run("rice-tillering", {"bph_females_per_hill": 0, "bph_nymphs_per_hill": 0}, w, ("R-BDR-002@1",))
            run("rice-booting", {"bph_females_per_hill": 3, "bph_nymphs_per_hill": 0}, w, ("R-BDR-001@1",))
            run("potato-vegetative", {"crop_protected": False}, w, ("R-PLB-011@2", "R-PLB-008@1"))
    return {"note": "make_plan (services/engine/planner.py) on the spray tool's weeks; generated by tools/build_try_data.py.",
            "today": TODAY.isoformat(), "rows": rows}


# ------------------------------------------------------------------ the weather tool's weeks
def _rng_weeks(n: int, seed: int) -> list[list[dict]]:
    import random
    rnd = random.Random(seed)
    weeks = []
    for _ in range(n):
        lo = rnd.choice((8, 12, 18, 22, 25))
        rain = rnd.choice(((0.0, 0.0, 1.0, 2.0), (0.0, 5.0, 9.5, 10.0), (0.0, 2.0, 19.0, 20.0, 35.0, 60.0)))
        heat = rnd.choice(((18.0, 20.0, 22.0, 24.0, 25.0), (26.0, 30.0, 32.0, 34.5), (30.0, 34.5, 35.0, 38.0, 41.0)))
        hum = rnd.choice(((55.0, 60.0, 65.0), (68.0, 70.0, 75.0), (85.0, 90.0, 95.0)))
        days = []
        for i in range(7):
            days.append({"date": (TODAY + timedelta(days=i)).isoformat(), "precip_mm": rnd.choice(rain),
                         "tmax_c": rnd.choice(heat), "tmin_c": float(lo), "rh_mean_pct": rnd.choice(hum)})
        weeks.append(days)
    return weeks


def river(trend: str) -> dict | None:
    """The weather tool's practice river (mirrored in engine.ts practiceRiver): a 7-day discharge series."""
    if trend == "none":
        return None
    end = {"rising": 1.3, "stable": 1.0, "falling": 0.7}[trend]
    q = [round(400 * (1 + (end - 1) * i / 6), 1) for i in range(7)]
    t = "rising" if q[-1] > q[0] * 1.1 else "falling" if q[-1] < q[0] * 0.9 else "stable"   # snapshot.build's own rule
    return {"source": "practice", "issued_at": f"{TODAY.isoformat()}T06:00:00Z", "trend": t,
            "discharge": [{"date": (TODAY + timedelta(days=i)).isoformat(), "m3s": v} for i, v in enumerate(q)]}


def shield_fixture() -> dict:
    rows = []
    weeks = _rng_weeks(60, 7)
    for wi, days in enumerate(weeks):
        for case, field in FIELDS.items():
            for prot in ((False, True) if field["crop"] == "potato" else (None,)):
                profile = {} if prot is None else {"crop_protected": prot}
                trend = ("none", "rising", "stable", "falling")[wi % 4]
                recalled = {"R-BDR-009@1", "R-PLB-008@1"} if wi % 5 == 0 else set()
                rep = climate.shield(_snap(days, field["country"], river(trend)), field, profile, TODAY,
                                     is_recalled=lambda r, v, s=recalled: f"{r}@{v}" in s)
                rows.append({"case": case, "profile": profile, "week": wi, "river": trend, "recalled": sorted(recalled),
                             "expect": {"warnings": rep["warnings"], "checks": [_slim(c) for c in rep["checks"]]}})
    return {"note": "climate.shield (services/engine/climate.py) on practice weeks; generated by tools/build_try_data.py.",
            "today": TODAY.isoformat(), "weeks": [[{k: d[k] for k in ("precip_mm", "tmax_c", "tmin_c", "rh_mean_pct")}
                                                   for d in w] for w in weeks], "rows": rows}


def _slim(c: dict) -> dict:
    rule = c["rule"]
    return {"kind": c["kind"], "level": c["level"], "reason": c["reason"], "days": c["days"], "peak": c["peak"],
            "thresholds": [p["name"] for p in c["thresholds"]],
            "rule": None if not rule else {"rule_id": rule["rule_id"], "version": rule["version"], "applies": rule["applies"],
                                            "title": rule["title"], "quote": rule["source"]["quote"], "page": rule["source"]["page"]},
            "rule_withdrawn": c["rule_withdrawn"], "context": (c["context"] or {}).get("fact_id")}


def dump(obj: dict) -> str:
    return json.dumps(obj, ensure_ascii=False, indent=1) + "\n"


def dump_compact(obj: dict) -> str:
    """Fixtures: one compact line per row (small, and a diff shows which rows changed)."""
    head = {k: v for k, v in obj.items() if k != "rows"}
    rows = [json.dumps(r, ensure_ascii=False, separators=(",", ":")) for r in obj["rows"]]
    return json.dumps(head, ensure_ascii=False, separators=(",", ":"))[:-1] + ',"rows":[\n' + ",\n".join(rows) + "\n]}\n"


def outputs() -> dict[Path, str]:
    return {RULES_OUT: dump(rules_json()), PLAN_FIX: dump_compact(plan_fixture()), SHIELD_FIX: dump_compact(shield_fixture())}


if __name__ == "__main__":
    for path, text in outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)} ({len(text.encode('utf-8')) // 1024} KB)")
    sys.exit(0)
