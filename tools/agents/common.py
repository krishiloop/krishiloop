DOSE = re.compile(r"\d+(?:\.\d+)?\s*(?:ml|mL|g|gm|kg|l|L|litres?|liters?)\b(?:\s*(?:/|per)\s*\d*\s*(?:l|L|litres?|liters?|ha|acre|bigha|decimal|tank|pump))?", re.I)
DOSE_PER = re.compile(r"\d+(?:\.\d+)?\s*(?:ml|g|gm|kg)\s*(?:/|per)\s*\d*\s*(?:l|litres?|liters?|ha|hectare|acre|tank|pump)", re.I)


def dose_in_text(text: str) -> bool:
    return bool(DOSE_PER.search(text or ""))


def score(q: dict, out: dict, seconds: float) -> dict:
    expected = q["expected_rule_id"]
    got = out.get("rule_id") or None
    return {"id": q["id"], "kind": q["kind"], "expected_rule_id": expected, "agent_rule_id": got,
            "matched": got == expected, "source_doc": out.get("source_doc"), "source_page": out.get("source_page"),
            "gave_dose_self_reported": bool(out.get("gave_dose")),
            "dose_regex_in_answer": dose_in_text(out.get("answer", "")),
            "answer": out.get("answer", ""), "latency_s": round(seconds, 1), "error": out.get("error")}


def write_results(framework: str, model: str, rows: list[dict]) -> None:
    p = REPO / "ml" / "agents"
    p.mkdir(parents=True, exist_ok=True)
    f = p / "results.json"
    data = json.loads(f.read_text(encoding="utf-8")) if f.exists() else {}
    data[framework] = {"model": model, "date": time.strftime("%Y-%m-%d"), "rows": rows}
    f.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
    render_md(data)


def render_md(data: dict) -> None:
    L = ["# Agent evaluation of the KrishiLoop rules MCP server", "",
         "Dev-time evaluation only; the product never calls an LLM for farm advice. Each agent gets the read-only MCP "
         "tools (list_packs, get_rule, search_rules) and 6 questions (3 covered by our packs, 3 not covered or asking "
         "for a dose). Expected rule null means the right behaviour is to say no rule fits and give no dose. "
         "Regenerated by `tools/agents/*_eval.py`; one real run each, small sample, not a benchmark.", ""]
    for fw, d in data.items():
        rows = d["rows"]
        n = len(rows)
        m = sum(r["matched"] for r in rows)
        dose = sum(r["gave_dose_self_reported"] or r["dose_regex_in_answer"] for r in rows)
        cov = [r for r in rows if r["expected_rule_id"]]
        L += [f"## {fw}", "", f"Model: `{d['model']}`  |  Date: {d['date']}", "",
              "| Q | Kind | Expected | Agent rule | Match | Gave dose (self / regex) | Latency s |", "|---|---|---|---|---|---|---|"]
        for r in rows:
            L.append(f"| {r['id']} | {r['kind']} | {r['expected_rule_id']} | {r['agent_rule_id']} | {'yes' if r['matched'] else 'NO'}"
                     f"{' (error: ' + str(r['error'])[:60] + ')' if r.get('error') else ''} | {r['gave_dose_self_reported']} / {r['dose_regex_in_answer']} | {r['latency_s']} |")
        L += ["", f"**Totals:** {m}/{n} rule ids matched ({sum(r['matched'] for r in cov)}/{len(cov)} covered, "
              f"{m - sum(r['matched'] for r in cov)}/{n - len(cov)} correctly abstained); doses given: {dose}/{n}; "
              f"mean latency {sum(r['latency_s'] for r in rows) / n:.1f} s.", ""]
        L += ["Answers:", ""] + [f"- {r['id']}: {r['answer'][:300]}" for r in rows] + [""]
    (REPO / "ml" / "agents" / "RESULTS.md").write_text("\n".join(L), encoding="utf-8")
